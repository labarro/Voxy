// Dev-only: converts the CC0 Quaternius packs into the avatar GLBs shipped with
// Voxy. Run once after changing the subset:
//   cd tools/avatar-assets && npm install
//   VOXY_UBC="<...>/Universal Base Characters[Standard]" \
//   VOXY_UAL="<...>/Universal Animation Library[Standard]/Unreal-Godot/UAL1_Standard.glb" \
//   node build.mjs
// Then refresh the manifest with `npm run assets:rooms3d` at the repo root.
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import {
  dedup,
  prune,
  resample,
  textureCompress,
  weld,
  mergeDocuments,
  unpartition,
} from "@gltf-transform/functions";
import sharp from "sharp";
import { mkdir, writeFile, stat } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../src/renderer/public/assets/room3d/avatars");
const ubc = process.env.VOXY_UBC;
const ual = process.env.VOXY_UAL;
if (!ubc || !ual) throw Error("Defina VOXY_UBC e VOXY_UAL.");
await mkdir(out, { recursive: true });
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const bodyDir = `${ubc}/Base Characters/Godot - UE`;
const hairDir = `${ubc}/Hairstyles/Rigged to Head Bone/glTF (Godot -Unreal)`;

// Normal maps keep more quality; colour maps are small stylized paintings.
const compress = (doc, size, slots) =>
  doc.transform(
    textureCompress({
      encoder: sharp,
      targetFormat: "webp",
      resize: [size, size],
      quality: 88,
      slots,
    }),
  );

async function body(file, name) {
  const doc = await io.read(`${bodyDir}/${file}`);
  // The pack ships both a "_png" and a plain normal texture name; the loader
  // only needs what the materials reference.
  await doc.transform(weld(), dedup(), prune());
  await compress(doc, 1024, /baseColor|normal/);
  await compress(doc, 512, /metallicRoughness|occlusion/);
  await doc.transform(unpartition());
  await io.write(`${out}/${name}.glb`, doc);
}

async function hair() {
  const names = [
    "Hair_SimpleParted",
    "Hair_Long",
    "Hair_Buns",
    "Hair_Buzzed",
    "Hair_BuzzedFemale",
    "Hair_Beard",
    "Eyebrows_Female",
    "Eyebrows_Regular",
  ];
  let doc;
  for (const n of names) {
    const part = await io.read(`${hairDir}/${n}.gltf`);
    // Name the mesh node after the source file so the renderer can pick it.
    for (const node of part.getRoot().listNodes())
      if (node.getMesh()) {
        node.setName(n);
        node.getMesh().setName(n);
      }
    if (!doc) doc = part;
    else mergeDocuments(doc, part);
  }
  await doc.transform(weld(), dedup(), prune());
  await compress(doc, 1024, /baseColor/);
  await compress(doc, 512, /normal/);
  await doc.transform(unpartition());
  await io.write(`${out}/hair.glb`, doc);
}

async function animations() {
  const keep = new Set([
    "Idle_Loop",
    "Idle_Talking_Loop",
    "Walk_Loop",
    "Jog_Fwd_Loop",
    "Sitting_Enter",
    "Sitting_Exit",
    "Sitting_Idle_Loop",
    "Sitting_Talking_Loop",
    "Dance_Loop",
    "Interact",
    "PickUp_Table",
    "Crouch_Idle_Loop",
    "Jump_Loop",
    "Spell_Simple_Idle_Loop",
  ]);
  const doc = await io.read(ual);
  for (const anim of doc.getRoot().listAnimations())
    if (!keep.has(anim.getName())) anim.dispose();
  // Only the armature is needed; the mannequin mesh is not shipped.
  for (const node of doc.getRoot().listNodes())
    if (node.getMesh()) {
      node.getMesh().dispose();
      node.setMesh(null);
      node.setSkin(null);
    }
  await doc.transform(resample({ tolerance: 0.0005 }), dedup(), prune({ keepLeaves: true }));
  await io.write(`${out}/animations.glb`, doc);
}

await body("Superhero_Male_FullBody.gltf", "body-m");
await body("Superhero_Female_FullBody.gltf", "body-f");
await hair();
await animations();
for (const f of ["body-m", "body-f", "hair", "animations"])
  console.log(f, (await stat(`${out}/${f}.glb`)).size);
await writeFile(
  `${out}/LICENSE.txt`,
  `Voxy avatar models and animations

Base characters, hairstyles, eyebrows, beard and animation clips are derived from
"Universal Base Characters" (Standard) and "Universal Animation Library"
(Standard) by Quaternius (https://quaternius.com), released under
CC0 1.0 Universal (Public Domain Dedication):
https://creativecommons.org/publicdomain/zero/1.0/

The files were converted to GLB, textures were resized/re-encoded as WebP and
only a subset of the animation clips is included. Clothing shells, extra
hairstyles, jaw/eye rigging, accessories and materials are generated by Voxy at
runtime. Credit is given voluntarily; no endorsement is implied.
`,
);
